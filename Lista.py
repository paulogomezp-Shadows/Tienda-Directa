# 1. Tu base de datos (Lista)
clientes_registrados = ["Paulo", "Ana", "Carlos", "María", "Pedro"]

print("--- INICIANDO SISTEMA DE ENVÍOS ---\n")

# 2. El Bucle FOR: La magia de la automatización
# Esto se lee así: "Por cada 'cliente' dentro de 'clientes_registrados', haz lo siguiente:"
for cliente in clientes_registrados:
    print("Generando etiqueta de envío para:", cliente)
    
print("\n--- TODOS LOS ENVÍOS HAN SIDO PROCESADOS ---")